"""
Model Evaluation Module for RoadWatch AI.
Evaluates YOLOv8n pothole detector on the held-out test split
and generates verified quantitative metrics and visual plots.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import time
from typing import Any, Dict
import pandas as pd
import torch

try:
    from ultralytics import YOLO
    ULTRALYTICS_AVAILABLE = True
except ImportError:
    ULTRALYTICS_AVAILABLE = False


def evaluate_model(
    model_path: str = "models/best.pt",
    data_yaml: str = "data/dataset.yaml",
    split: str = "test",
    img_size: int = 640,
    device: str = None,
    output_metrics_file: str = "outputs/metrics/evaluation_metrics.json",
    output_plots_dir: str = "outputs/plots",
) -> Dict[str, Any]:
    """
    Evaluates the trained YOLOv8n model on the specified split (held-out test split).
    """
    if not ULTRALYTICS_AVAILABLE:
        raise ImportError(
            "Ultralytics is not installed. Run `pip install ultralytics`"
        )

    model_file = Path(model_path)
    if not model_file.is_file():
        raise FileNotFoundError(
            f"Trained model checkpoint '{model_path}' not found. "
            "Please run `python src/train.py` first to train and produce models/best.pt."
        )

    data_file = Path(data_yaml)
    if not data_file.is_file():
        raise FileNotFoundError(
            f"Dataset configuration '{data_yaml}' not found. "
            "Please run `python src/dataset.py` first to generate data splits."
        )

    if device is None:
        device = "0" if torch.cuda.is_available() else "cpu"

    print("\n" + "=" * 60)
    print(" RoadWatch AI - Model Evaluation Pipeline")
    print("=" * 60)
    print(f" Model Weights : {model_file.resolve()}")
    print(f" Dataset Config: {data_file.resolve()}")
    print(f" Target Split  : {split}")
    print(f" Device        : {device}")
    print("=" * 60 + "\n")

    # Load model
    model = YOLO(str(model_file))

    # Run validation on the specified split (e.g. 'test')
    t_start = time.perf_counter()
    metrics = model.val(
        data=str(data_file),
        split=split,
        imgsz=img_size,
        device=device,
        plots=True,
        verbose=True,
    )
    eval_duration = time.perf_counter() - t_start

    # Extract quantitative metrics
    box_metrics = metrics.box
    precision = float(box_metrics.mp)  # mean precision
    recall = float(box_metrics.mr)     # mean recall
    map50 = float(box_metrics.map50)   # mAP @ 0.5 IoU
    map50_95 = float(box_metrics.map)  # mAP @ 0.5:0.95 IoU

    # Calculate F1 score
    if (precision + recall) > 0:
        f1_score = float(2 * (precision * recall) / (precision + recall))
    else:
        f1_score = 0.0

    # Extract speed metrics if present
    speed = metrics.speed
    inference_ms = float(speed.get("inference", 0.0))
    preprocess_ms = float(speed.get("preprocess", 0.0))
    postprocess_ms = float(speed.get("postprocess", 0.0))
    total_latency_ms = inference_ms + preprocess_ms + postprocess_ms

    results_data = {
        "model_name": "YOLOv8n-Pothole",
        "target_class": "pothole",
        "evaluation_split": split,
        "metrics": {
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1_score": round(f1_score, 4),
            "map_50": round(map50, 4),
            "map_50_95": round(map50_95, 4),
        },
        "latency_ms": {
            "preprocess": round(preprocess_ms, 2),
            "inference": round(inference_ms, 2),
            "postprocess": round(postprocess_ms, 2),
            "total_per_image": round(total_latency_ms, 2),
        },
        "evaluation_device": device,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }

    # Save to JSON
    out_json = Path(output_metrics_file)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    with open(out_json, "w", encoding="utf-8") as jf:
        json.dump(results_data, jf, indent=4)

    # Save summary CSV
    summary_csv = out_json.parent / "evaluation_summary.csv"
    flat_metrics = {
        "Metric": ["Precision", "Recall", "F1-Score", "mAP@0.5", "mAP@0.5:0.95", "Inference Latency (ms)"],
        "Value": [
            results_data["metrics"]["precision"],
            results_data["metrics"]["recall"],
            results_data["metrics"]["f1_score"],
            results_data["metrics"]["map_50"],
            results_data["metrics"]["map_50_95"],
            results_data["latency_ms"]["total_per_image"],
        ],
    }
    pd.DataFrame(flat_metrics).to_csv(summary_csv, index=False)

    # Copy evaluation plots if generated by Ultralytics
    plots_dst = Path(output_plots_dir)
    plots_dst.mkdir(parents=True, exist_ok=True)

    val_save_dir = Path(metrics.save_dir)
    for plot_file in val_save_dir.glob("*.png"):
        shutil.copy2(plot_file, plots_dst / plot_file.name)
        print(f"Copied plot {plot_file.name} to {plots_dst}")

    print("\n[Success] Model evaluation finished!")
    print(f"  Precision    : {results_data['metrics']['precision']:.4f}")
    print(f"  Recall       : {results_data['metrics']['recall']:.4f}")
    print(f"  F1-Score     : {results_data['metrics']['f1_score']:.4f}")
    print(f"  mAP@0.5      : {results_data['metrics']['map_50']:.4f}")
    print(f"  mAP@0.5:0.95 : {results_data['metrics']['map_50_95']:.4f}")
    print(f"  Inference    : {results_data['latency_ms']['total_per_image']:.2f} ms")
    print(f"Metrics saved to: {out_json.resolve()}")

    return results_data


def main():
    parser = argparse.ArgumentParser(description="Evaluate YOLOv8n Pothole Detector")
    parser.add_argument("--model", type=str, default="models/best.pt", help="Path to best.pt")
    parser.add_argument("--data", type=str, default="data/dataset.yaml", help="Path to dataset.yaml")
    parser.add_argument("--split", type=str, default="test", help="Split to evaluate: test or val")
    parser.add_argument("--imgsz", type=int, default=640, help="Evaluation image size")
    parser.add_argument("--device", type=str, default=None, help="Evaluation device (cuda or cpu)")
    args = parser.parse_args()

    evaluate_model(
        model_path=args.model,
        data_yaml=args.data,
        split=args.split,
        img_size=args.imgsz,
        device=args.device,
    )


if __name__ == "__main__":
    main()
